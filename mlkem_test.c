static void check(int ok, const char *what, int id)
{
    if (ok) {
        pass_count++;
    } else {
        fail_count++;
        printf("FAIL  %s %s #%d\n", MLKEM_NAME, what, id);
    }
}

//  decode a hex string of exactly len bytes
static void unhex(uint8_t *buf, size_t len, const char *hex)
{
    size_t i;
    unsigned x;

    if (strlen(hex) != 2 * len) {
        printf("BAD TEST DATA: expected %zu hex digits, got %zu\n",
               2 * len, strlen(hex));
        fail_count++;
        memset(buf, 0, len);
        return;
    }
    for (i = 0; i < len; i++) {
        sscanf(hex + 2 * i, "%2x", &x);
        buf[i] = (uint8_t) x;
    }
}

static int eq_hex(const uint8_t *buf, size_t len, const char *hex)
{
    uint8_t ref[64];
    unhex(ref, len, hex);
    return memcmp(buf, ref, len) == 0;
}

static int eq_sha3(const uint8_t *buf, size_t len, const char *hex)
{
    uint8_t h[32];
    sha3_256(h, buf, len);
    return eq_hex(h, 32, hex);
}

//  output buffers carry a canary tail that must survive each call
static void guard_set(uint8_t *buf, size_t len)
{
    memset(buf + len, 0xA5, GUARD);
}

static int guard_ok(const uint8_t *buf, size_t len)
{
    size_t i;
    for (i = 0; i < GUARD; i++)
        if (buf[len + i] != 0xA5)
            return 0;
    return 1;
}

//  === tests

static void test_keccak(void)
{
    //  SHA3-256("abc"), FIPS 202 example; validates the reference Keccak
    uint8_t h[32];
    sha3_256(h, (const uint8_t *) "abc", 3);
    check(eq_hex(h, 32, "3a985da74fe225b2045c172d6bd390bd"
                        "855f086e3e9d525b46bfe24511431532"), "C SHA3 self-test", 0);
}

static void test_keygen(void)
{
    uint8_t d[32], z[32], d0[32], z0[32];
    static uint8_t ek[EK_BYTES + GUARD], dk[DK_BYTES + GUARD];
    size_t i;

    for (i = 0; i < NUM(kat_keygen); i++) {
        unhex(d, 32, kat_keygen[i].d);
        unhex(z, 32, kat_keygen[i].z);
        memcpy(d0, d, 32);
        memcpy(z0, z, 32);
        guard_set(ek, EK_BYTES);
        guard_set(dk, DK_BYTES);
        mlkem_keygen(ek, dk, d, z);
        check(eq_sha3(ek, EK_BYTES, kat_keygen[i].ek_sha3), "KeyGen ek", i);
        check(eq_sha3(dk, DK_BYTES, kat_keygen[i].dk_sha3), "KeyGen dk", i);
        check(guard_ok(ek, EK_BYTES) && guard_ok(dk, DK_BYTES),
              "KeyGen output overrun", i);
        check(!memcmp(d, d0, 32) && !memcmp(z, z0, 32),
              "KeyGen input modified", i);
    }
}

static void test_encaps(void)
{
    static uint8_t ek[EK_BYTES], ek0[EK_BYTES], ct[CT_BYTES + GUARD];
    uint8_t m[32], m0[32], k[32 + GUARD];
    size_t i;

    for (i = 0; i < NUM(kat_encaps); i++) {
        unhex(ek, EK_BYTES, kat_encaps[i].ek);
        unhex(m, 32, kat_encaps[i].m);
        memcpy(ek0, ek, EK_BYTES);
        memcpy(m0, m, 32);
        guard_set(ct, CT_BYTES);
        guard_set(k, 32);
        mlkem_encaps(ct, k, ek, m);
        check(eq_hex(k, 32, kat_encaps[i].k), "Encaps K", i);
        check(eq_sha3(ct, CT_BYTES, kat_encaps[i].c_sha3), "Encaps c", i);
        check(guard_ok(ct, CT_BYTES) && guard_ok(k, 32),
              "Encaps output overrun", i);
        check(!memcmp(ek, ek0, EK_BYTES) && !memcmp(m, m0, 32),
              "Encaps input modified", i);
    }
}

static void test_decaps(void)
{
    static uint8_t dk[DK_BYTES], dk0[DK_BYTES], ct[CT_BYTES], ct0[CT_BYTES];
    uint8_t k[32 + GUARD];
    size_t i;

    unhex(dk, DK_BYTES, kat_decaps_dk);
    memcpy(dk0, dk, DK_BYTES);
    for (i = 0; i < NUM(kat_decaps); i++) {
        unhex(ct, CT_BYTES, kat_decaps[i].c);
        memcpy(ct0, ct, CT_BYTES);
        guard_set(k, 32);
        mlkem_decaps(k, ct, dk);
        check(eq_hex(k, 32, kat_decaps[i].k),
              kat_decaps[i].valid ? "Decaps K (valid c)" :
                                    "Decaps K (modified c, implicit reject)", i);
        check(guard_ok(k, 32), "Decaps output overrun", i);
        check(!memcmp(ct, ct0, CT_BYTES) && !memcmp(dk, dk0, DK_BYTES),
              "Decaps input modified", i);
    }
}

static void test_roundtrip_reject(void)
{
    static uint8_t ek[EK_BYTES], dk[DK_BYTES], ct[CT_BYTES], bad[CT_BYTES];
    static uint8_t zc[32 + CT_BYTES];
    uint8_t d[32], z[32], m[32], k1[32], k2[32], kbar[32];
    //  bit flips: start/end of the u part, start/middle/end of the v part
    const size_t pos[] = { 0, 32 * DU * MLKEM_K - 1, 32 * DU * MLKEM_K,
                           CT_BYTES - 16, CT_BYTES - 1 };
    size_t i;

    unhex(d, 32, kat_keygen[0].d);
    unhex(z, 32, kat_keygen[0].z);
    unhex(m, 32, kat_encaps[0].m);
    mlkem_keygen(ek, dk, d, z);
    mlkem_encaps(ct, k1, ek, m);
    mlkem_decaps(k2, ct, dk);
    check(!memcmp(k1, k2, 32), "Round trip K", 0);

    for (i = 0; i < NUM(pos); i++) {
        memcpy(bad, ct, CT_BYTES);
        bad[pos[i]] ^= (uint8_t) (1 << (i % 8));
        mlkem_decaps(k2, bad, dk);
        memcpy(zc, z, 32);
        memcpy(zc + 32, bad, CT_BYTES);
        shake256(kbar, 32, zc, sizeof(zc));     //  J(z || c')
        check(!memcmp(k2, kbar, 32) && memcmp(k2, k1, 32),
              "Implicit reject (bit flip)", (int) pos[i]);
    }
}

static void test_bulk(void)
{
    static uint8_t ek[EK_BYTES], dk[DK_BYTES], ct[CT_BYTES], bad[CT_BYTES];
    static uint8_t zc[32 + CT_BYTES], buf[32 * 6];
    uint8_t ctr[4], coins[99], k[32], k2[32], kbar[32];
    unsigned i, pos;
    int roundtrip_ok = 1, reject_ok = 1;

    memset(buf, 0, 32);                         //  acc = 0
    for (i = 0; i < BULK_N; i++) {
        ctr[0] = i;                             //  coins = SHAKE256(i, 99)
        ctr[1] = i >> 8;
        ctr[2] = i >> 16;
        ctr[3] = i >> 24;
        shake256(coins, sizeof(coins), ctr, 4);
        mlkem_keygen(ek, dk, coins, coins + 32);
        mlkem_encaps(ct, k, ek, coins + 64);
        mlkem_decaps(k2, ct, dk);
        roundtrip_ok &= !memcmp(k, k2, 32);

        pos = (coins[96] + 256u * coins[97]) % CT_BYTES;
        memcpy(bad, ct, CT_BYTES);
        bad[pos] ^= (uint8_t) (1 << (coins[98] & 7));
        mlkem_decaps(k2, bad, dk);
        memcpy(zc, coins + 32, 32);
        memcpy(zc + 32, bad, CT_BYTES);
        shake256(kbar, 32, zc, sizeof(zc));
        reject_ok &= !memcmp(k2, kbar, 32);

        //  acc = H(acc || H(ek) || H(dk) || H(c) || K || K_reject)
        sha3_256(buf + 32, ek, EK_BYTES);
        sha3_256(buf + 64, dk, DK_BYTES);
        sha3_256(buf + 96, ct, CT_BYTES);
        memcpy(buf + 128, k, 32);
        memcpy(buf + 160, k2, 32);
        sha3_256(buf, buf, sizeof(buf));
    }
    check(roundtrip_ok, "Bulk round trip K", BULK_N);
    check(reject_ok, "Bulk implicit reject", BULK_N);
    check(eq_hex(buf, 32, kat_bulk_digest), "Bulk digest vs fips203.py", BULK_N);
}

int main(void)
{
    printf("%s: ek=%d dk=%d ct=%d bytes\n",
           MLKEM_NAME, EK_BYTES, DK_BYTES, CT_BYTES);
    test_keccak();
    test_keygen();
    test_encaps();
    test_decaps();
    test_roundtrip_reject();
    test_bulk();
    printf("%s: PASS= %d  FAIL= %d\n", MLKEM_NAME, pass_count, fail_count);
    return fail_count;
}
