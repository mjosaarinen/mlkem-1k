//  mlkem_test.c
//  === Self-contained test harness for mlkem.S (ML-KEM, FIPS 203).
//
//  gcc -O2 -DMLKEM_K=2 mlkem_test.c mlkem.S -o mlkem512_test   (or K=3, 4)
//
//  1.  ACVP KeyGen vectors: (d, z) -> SHA3-256 of ek and dk.
//  2.  ACVP Encaps vectors: (ek, m) -> K and SHA3-256 of c.
//  3.  ACVP Decaps vectors, both valid and modified ciphertexts -> K.
//  4.  Round trip with the first keygen vector, then implicit rejection
//      for several single-bit ciphertext flips. The expected rejection key
//      J(z || c') = SHAKE256(z || c', 32) is computed here, independently,
//      with a small C Keccak.
//  5.  Bulk: BULK_N keygen / encaps / decaps / bit-flip reject cycles with
//      seeds from SHAKE256(counter), folded into one SHA3-256 digest that
//      gen_kat.py computes with the py-acvp-pqc reference model (fips203.py).
//      This catches rare-case bugs (e.g. rounding at a single residue).
//  Every call also checks that no output was written past its end and no
//  input was modified. The exit status is the number of failures.
//
//  Test vectors are from NIST's ACVP-Server JSON files (via py-acvp-pqc);
//  regenerate the block between the BEGIN/END markers with gen_kat.py.

