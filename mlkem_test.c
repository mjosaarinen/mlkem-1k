//  === independent reference Keccak (little-endian host)

static uint64_t rol64(uint64_t x, int n)
{
    return (x << n) | (x >> (64 - n));          //  n is never 0 here
}

static void keccak_f1600(uint64_t s[25])
{
    static const uint64_t rc[24] = {
        0x0000000000000001, 0x0000000000008082, 0x800000000000808A,
        0x8000000080008000, 0x000000000000808B, 0x0000000080000001,
        0x8000000080008081, 0x8000000000008009, 0x000000000000008A,
        0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
        0x000000008000808B, 0x800000000000008B, 0x8000000000008089,
        0x8000000000008003, 0x8000000000008002, 0x8000000000000080,
        0x000000000000800A, 0x800000008000000A, 0x8000000080008081,
        0x8000000000008080, 0x0000000080000001, 0x8000000080008008 };
    static const int rotc[24] = {
        1,  3,  6,  10, 15, 21, 28, 36, 45, 55, 2,  14,
        27, 41, 56, 8,  25, 43, 62, 18, 39, 61, 20, 44 };
    static const int piln[24] = {
        10, 7,  11, 17, 18, 3,  5,  16, 8,  21, 24, 4,
        15, 23, 19, 13, 12, 2,  20, 14, 22, 9,  6,  1 };
    uint64_t bc[5], t;
    int r, i, j;

    for (r = 0; r < 24; r++) {
        for (i = 0; i < 5; i++)
            bc[i] = s[i] ^ s[i + 5] ^ s[i + 10] ^ s[i + 15] ^ s[i + 20];
        for (i = 0; i < 5; i++) {
            t = bc[(i + 4) % 5] ^ rol64(bc[(i + 1) % 5], 1);
            for (j = 0; j < 25; j += 5)
                s[j + i] ^= t;
        }
        t = s[1];
        for (i = 0; i < 24; i++) {
            j = piln[i];
            bc[0] = s[j];
            s[j] = rol64(t, rotc[i]);
            t = bc[0];
        }
        for (j = 0; j < 25; j += 5) {
            for (i = 0; i < 5; i++)
                bc[i] = s[j + i];
            for (i = 0; i < 5; i++)
                s[j + i] ^= (~bc[(i + 1) % 5]) & bc[(i + 2) % 5];
        }
        s[0] ^= rc[r];
    }
}

//  one-shot sponge; rate in bytes, pad = 0x06 (SHA3) or 0x1F (SHAKE)
static void keccak(uint8_t *out, size_t outlen, const uint8_t *in,
                   size_t inlen, size_t rate, uint8_t pad)
{
    uint64_t s[25] = { 0 };
    uint8_t *b = (uint8_t *) s;
    size_t i, j = 0;

    for (i = 0; i < inlen; i++) {
        b[j++] ^= in[i];
        if (j == rate) {
            keccak_f1600(s);
            j = 0;
        }
    }
    b[j] ^= pad;
    b[rate - 1] ^= 0x80;
    keccak_f1600(s);
    for (i = j = 0; i < outlen; i++) {
        if (j == rate) {
            keccak_f1600(s);
            j = 0;
        }
        out[i] = b[j++];
    }
}

static void sha3_256(uint8_t h[32], const uint8_t *in, size_t len)
{
    keccak(h, 32, in, len, 136, 0x06);
}

static void shake256(uint8_t *out, size_t outlen, const uint8_t *in, size_t len)
{
    keccak(out, outlen, in, len, 136, 0x1F);
}

