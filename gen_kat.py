#   gen_kat.py
#   === Emit the C test-vector block of mlkem_test.c from NIST ACVP JSON.
#
#   python3 gen_kat.py [json-dir] > kat_block.txt
#
#   Default json-dir: ../py-acvp-pqc/json-copy (local copy of ACVP-Server
#   gen-val/json-files). Inputs are emitted in full; large outputs (ek, dk,
#   c) are replaced by their SHA3-256 hash. Shared keys K are kept in full.
#
#   It also emits a "bulk" digest computed with the py-acvp-pqc reference
#   model (fips203.py): BULK_N keygen / encaps / decaps / implicit-reject
#   cycles from counter-derived seeds, mirrored by test_bulk() in C.

import hashlib, json, os, sys

JSON_DIR = sys.argv[1] if len(sys.argv) > 1 else '../py-acvp-pqc/json-copy'
REF_DIR = os.path.dirname(os.path.abspath(JSON_DIR))   # py-acvp-pqc
BULK_N = 256        # reference-model cycles per parameter set

N_KEYGEN = 2        # keygen vectors per parameter set
N_ENCAPS = 1        # encaps vectors per parameter set (ek is large)
N_DECAPS = 2        # decaps vectors per kind: valid / modified ciphertext

K_OF = { 'ML-KEM-512': 2, 'ML-KEM-768': 3, 'ML-KEM-1024': 4 }

def load(name):
    """Merge prompt, expected results and internal projection by tcId."""
    files = [ 'prompt', 'expectedResults', 'internalProjection' ]
    js = [ json.load(open(f'{JSON_DIR}/{name}/{f}.json')) for f in files ]
    groups = []
    for qtg in js[0]['testGroups']:
        tests = { t['tcId']: dict(t) for t in qtg['tests'] }
        for extra in js[1:]:
            for tg in extra['testGroups']:
                if tg['tgId'] == qtg['tgId']:
                    for t in tg['tests']:
                        tests[t['tcId']].update(t)
        groups += [ (qtg, [ tests[i] for i in sorted(tests) ]) ]
    return groups

def sha3(h):
    return hashlib.sha3_256(bytes.fromhex(h)).hexdigest()

def cstr(h, ind='        '):
    """Hex string as concatenated C string literals, 128 chars per line."""
    h = h.lower()
    if len(h) <= 64:
        return f'"{h}"'
    return '\n'.join(f'{ind}"{h[i:i+128]}"' for i in range(0, len(h), 128))

def bulk_digest(ps, n):
    """Same computation as test_bulk() in mlkem_test.c."""
    cwd = os.getcwd()
    os.chdir(REF_DIR)                   # fips203.py loads json-copy/ on import
    sys.path.insert(0, REF_DIR)
    from fips203 import ML_KEM
    os.chdir(cwd)
    kem = ML_KEM(ps)
    h = lambda x: hashlib.sha3_256(x).digest()
    acc = bytes(32)
    for i in range(n):
        coins = hashlib.shake_256(i.to_bytes(4, 'little')).digest(99)
        (d, z, m) = (coins[0:32], coins[32:64], coins[64:96])
        (ek, dk) = kem.keygen_internal(d, z)
        (k, c) = kem.encaps_internal(ek, m)
        assert kem.decaps_internal(dk, c) == k
        pos = (coins[96] + 256 * coins[97]) % len(c)
        bad = bytearray(c)
        bad[pos] ^= 1 << (coins[98] & 7)
        kr = kem.decaps_internal(dk, bytes(bad))
        acc = h(acc + h(ek) + h(dk) + h(c) + k + kr)
    return acc.hex()

keygen = load('ML-KEM-keyGen-FIPS203')
encdec = load('ML-KEM-encapDecap-FIPS203')

out = []
out += [ '//  --- BEGIN generated by gen_kat.py from NIST ACVP-Server JSON',
         '//  ML-KEM-keyGen-FIPS203 and ML-KEM-encapDecap-FIPS203 (vsId '
            + str(json.load(open(f'{JSON_DIR}/ML-KEM-keyGen-FIPS203/prompt.json'))['vsId']) + ').' ]

first = True
for ps, k in K_OF.items():
    out += [ '', ('#if' if first else '#elif') + f'   MLKEM_K == {k}  //  {ps}' ]
    first = False

    #   keygen: d, z -> SHA3-256(ek), SHA3-256(dk)
    (tg, tests) = [ g for g in keygen if g[0]['parameterSet'] == ps ][0]
    out += [ '', 'static const kat_keygen_t kat_keygen[] = {' ]
    for t in tests[:N_KEYGEN]:
        out += [ f'    {{   //  tgId={tg["tgId"]} tcId={t["tcId"]}',
                 f'        {cstr(t["d"])},',
                 f'        {cstr(t["z"])},',
                 f'        {cstr(sha3(t["ek"]))},   //  SHA3-256(ek)',
                 f'        {cstr(sha3(t["dk"]))} }},  //  SHA3-256(dk)' ]
    out += [ '};' ]

    #   encaps: ek, m -> K, SHA3-256(c)
    (tg, tests) = [ g for g in encdec if g[0]['parameterSet'] == ps
                        and g[0]['function'] == 'encapsulation' ][0]
    out += [ '', 'static const kat_encaps_t kat_encaps[] = {' ]
    for t in tests[:N_ENCAPS]:
        out += [ f'    {{   //  tgId={tg["tgId"]} tcId={t["tcId"]}',
                 cstr(t['ek']) + ',',
                 f'        {cstr(t["m"])},',
                 f'        {cstr(t["k"])},  //  K',
                 f'        {cstr(sha3(t["c"]))} }},  //  SHA3-256(c)' ]
    out += [ '};' ]

    #   decaps: shared dk; c -> K for valid and modified ciphertexts
    (tg, tests) = [ g for g in encdec if g[0]['parameterSet'] == ps
                        and g[0]['function'] == 'decapsulation' ][0]
    valid = [ t for t in tests if t['reason'] == 'valid decapsulation' ]
    bad = [ t for t in tests if t['reason'] == 'modified ciphertext' ]
    sel = []
    for i in range(N_DECAPS):
        sel += [ (valid[i], 1), (bad[i], 0) ]
    out += [ '', f'//  tgId={tg["tgId"]} decapsulation key (shared by the group)',
             'static const char kat_decaps_dk[] =', cstr(tg['dk']) + ';',
             '', 'static const kat_decaps_t kat_decaps[] = {' ]
    for (t, ok) in sel:
        out += [ f'    {{   //  tgId={tg["tgId"]} tcId={t["tcId"]}: {t["reason"]}',
                 cstr(t['c']) + ',',
                 f'        {cstr(t["k"])}, {ok} }},' ]
    out += [ '};' ]

    #   bulk: reference-model digest
    out += [ '', f'//  {ps}: digest of {BULK_N} reference-model (fips203.py) cycles',
             f'#define BULK_N {BULK_N}',
             f'static const char kat_bulk_digest[] = "{bulk_digest(ps, BULK_N)}";' ]

out += [ '', '#endif', '//  --- END generated by gen_kat.py' ]
print('\n'.join(out))
